import pandas as pd, json, sys, os
RAIZ = sys.argv[1] if len(sys.argv) > 1 else '.'
E = os.path.join(RAIZ, '01_Dados_Originais', 'base_complementar_ecommerce', ''); O = os.path.join(RAIZ, '01_Dados_Originais', 'base_original', '')
r=lambda p,f: pd.read_csv(p+f,sep=';',encoding='utf-8-sig')
v=r(O,'f_vendas.csv'); it=r(O,'f_itens_venda.csv'); cl=r(O,'dim_clientes.csv'); pr=r(O,'dim_produtos.csv'); lj=r(O,'dim_lojas.csv')
ped=r(E,'f_pedidos_digitais.csv'); ses=r(E,'f_sessoes_digitais.csv'); av=r(E,'f_avaliacoes_produto.csv'); ps=r(E,'f_pesquisas_satisfacao.csv')
cu=r(E,'f_custos_digitais_mensais.csv'); ab=r(E,'f_experimentos_ab.csv'); rm=r(E,'f_roadmap_iniciativas.csv')
dd=r(E,'dim_dispositivo.csv'); do=r(E,'dim_origem_trafego.csv'); dm=r(E,'dim_motivo_satisfacao.csv'); di=r(E,'dim_iniciativa.csv')
res=[]
def chk(n,ok,val=''):
    if not isinstance(ok,(bool,)) and not hasattr(ok,'dtype'): ok=bool(ok)
    ok = bool(ok == 1) if isinstance(ok,float) else bool(ok)
    res.append((n,'PASS' if ok else 'FAIL',str(val)))
dig=v[v.canal.isin(['Site','Aplicativo','Delivery'])]
chk('vendas digitais =40029',len(dig)==40029,len(dig))
chk('receita digital 9.774.295,05',round(dig.valor_liquido.sum(),2)==9774295.05,round(dig.valor_liquido.sum(),2))
chk('pedidos únicos id_venda',ped.id_venda.is_unique,len(ped))
chk('pedidos ⊂ vendas digitais e 1:1',set(ped.id_venda)==set(dig.id_venda))
m=ped.merge(v[['id_venda','canal','id_loja','data_venda']],on='id_venda',suffixes=('','_v'))
chk('canal/loja/data pedidos = vendas',(m.canal==m.canal_v).all() and (m.id_loja==m.id_loja_v).all() and (m.data_venda==m.data_venda_v).all())
chk('OTIF 87,8%',round(ped.otif.mean()*100,1)==87.8,round(ped.otif.mean()*100,2))
chk('otif coerente prazo_real<=prometido',((ped.prazo_real_dias<=ped.prazo_prometido_dias).astype(int)==ped.otif).mean(),((ped.prazo_real_dias<=ped.prazo_prometido_dias).astype(int)==ped.otif).mean())
chk('status_entrega valores',True,ped.status_entrega.value_counts().to_dict())
chk('sessoes 1.274.133',ses.sessoes.sum()==1274133,ses.sessoes.sum())
chk('pedidos em sessões =40029',ses.pedidos.sum()==40029,ses.pedidos.sum())
chk('conversão 3,14%',round(ses.pedidos.sum()/ses.sessoes.sum()*100,2)==3.14,round(ses.pedidos.sum()/ses.sessoes.sum()*100,3))
g1=ses.groupby(['data','id_loja','canal']).pedidos.sum(); g2=dig.groupby(['data_venda','id_loja','canal']).size(); g2.index.names=g1.index.names
j=pd.concat([g1,g2],axis=1).fillna(0); chk('pedidos sessão = vendas por dia×loja×canal',(j.iloc[:,0]==j.iloc[:,1]).all(),(j.iloc[:,0]!=j.iloc[:,1]).sum())
chk('funil monotônico (sess>=atc>=chk>=ped) linhas',((ses.sessoes>=ses.add_to_cart)&(ses.add_to_cart>=ses.iniciou_checkout)&(ses.iniciou_checkout>=ses.pedidos)).mean(),((ses.sessoes>=ses.add_to_cart)&(ses.add_to_cart>=ses.iniciou_checkout)&(ses.iniciou_checkout>=ses.pedidos)).mean())
chk('chave sessões única',not ses.duplicated(['data','id_loja','canal','id_dispositivo','id_origem']).any())
chk('FK dispositivo/origem',ses.id_dispositivo.isin(dd.id_dispositivo).all() and ses.id_origem.isin(do.id_origem).all())
chk('avaliações 13.324',len(av)==13324 and av.id_avaliacao.is_unique,len(av))
chk('notas usam escala 1-5 completa',av.nota.nunique()>=4,sorted(av.nota.unique().tolist()))
chk('nota média 3,98',round(av.nota.mean(),2)==3.98,round(av.nota.mean(),3))
chk('FK aval produto/cliente/venda',av.id_produto.isin(pr.id_produto).all() and av.id_cliente.isin(cl.id_cliente).all() and av.id_venda.isin(dig.id_venda).all())
ai=av.merge(it[['id_venda','id_produto']].drop_duplicates(),on=['id_venda','id_produto'],how='left',indicator=True)
chk('aval produto ∈ itens da venda',(ai._merge=='both').mean(),(ai._merge=='both').mean())
ac=av.merge(v[['id_venda','id_cliente']],on='id_venda',suffixes=('','_v'))
chk('aval cliente = cliente da venda',(ac.id_cliente==ac.id_cliente_v).mean(),(ac.id_cliente==ac.id_cliente_v).mean())
chk('aval data >= data venda',(pd.to_datetime(av.data_avaliacao)>=pd.to_datetime(av.merge(v[['id_venda','data_venda']],on='id_venda').data_venda)).mean(),'')
chk('pesquisas 7.482',len(ps)==7482 and ps.id_pesquisa.is_unique,len(ps))
nps=((ps.nps_score>=9).mean()-(ps.nps_score<=6).mean())*100
chk('NPS +5,9',round(nps,1)==5.9,round(nps,2))
chk('CSAT 4,41',round(ps.csat_score.mean(),2)==4.41,round(ps.csat_score.mean(),3))
chk('FK motivo',ps.id_motivo_principal.isin(dm.id_motivo).all())
chk('pesq venda digital',ps.id_venda.isin(dig.id_venda).all(), ps.id_venda.is_unique)
pc=ps.merge(v[['id_venda','id_cliente','canal','id_loja']],on='id_venda',suffixes=('','_v'))
chk('pesq cliente/canal/loja = venda',((pc.id_cliente==pc.id_cliente_v)&(pc.canal==pc.canal_v)&(pc.id_loja==pc.id_loja_v)).mean(),'')
chk('custo digital 1.736.490,06',round(cu.custo_digital_total.sum(),2)==1736490.06,round(cu.custo_digital_total.sum(),2))
chk('custo soma componentes',(abs(cu[['midia_paga','plataforma','fulfillment','outros_digitais']].sum(axis=1)-cu.custo_digital_total)<0.02).all())
dig2=dig.assign(am=dig.data_venda.str[:7]).groupby(['am','id_loja']).agg(rec=('valor_liquido','sum'),n=('id_venda','count')).reset_index()
cc=cu.merge(dig2,left_on=['ano_mes','id_loja'],right_on=['am','id_loja'])
chk('receita_digital_ref = f_vendas mês×loja',(abs(cc.receita_digital_ref-cc.rec)<0.02).all(),(abs(cc.receita_digital_ref-cc.rec)).max())
chk('pedidos_ref = vendas',(cc.pedidos_ref==cc.n).all())
fm=ped.assign(am=ped.data_venda.str[:7]).groupby(['am','id_loja']).custo_fulfillment.sum().reset_index()
cf=cu.merge(fm,left_on=['ano_mes','id_loja'],right_on=['am','id_loja'])
chk('fulfillment mensal = soma pedidos',(abs(cf.fulfillment-cf.custo_fulfillment)<1).mean(),abs(cf.fulfillment-cf.custo_fulfillment).max())
chk('roadmap 360 = 15×24 único',len(rm)==360 and not rm.duplicated(['id_iniciativa','ano_mes']).any())
chk('FK iniciativa',rm.id_iniciativa.isin(di.id_iniciativa).all())
chk('experimentos 14',len(ab)==14,ab.id_experimento.nunique())
chk('pct conclusão 0-100',rm.pct_conclusao.between(0,100).all())
# monotonic roadmap
mono=rm.sort_values(['id_iniciativa','ano_mes']).groupby('id_iniciativa').pct_conclusao.apply(lambda s:(s.diff().fillna(0)>=0).all())
chk('roadmap % não decresce',mono.all(),mono[~mono].index.tolist())
for n,s,val in res: print(f'{s:4} | {n} | {val}')
json.dump(res,open(os.path.join(RAIZ,'07_Testes','GATE_A_ecom.json'),'w'),ensure_ascii=False,indent=1,default=str)
